import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const COMPOUNDS = {
  glycine: ["L-glycine", 750],
  alanine: ["L-alanine", 5950],
  valine: ["L-valine", 6287],
  leucine: ["L-leucine", 6106],
  isoleucine: ["L-isoleucine", 6306],
  methionine: ["L-methionine", 6137],
  phenylalanine: ["L-phenylalanine", 6140],
  tryptophan: ["L-tryptophan", 6305],
  proline: ["L-proline", 145742],
  serine: ["L-serine", 5951],
  threonine: ["L-threonine", 6288],
  cysteine: ["L-cysteine", 5862],
  tyrosine: ["L-tyrosine", 6057],
  asparagine: ["L-asparagine", 6267],
  glutamine: ["L-glutamine", 5961],
  "aspartic-acid": ["L-aspartic acid", 5960],
  "glutamic-acid": ["L-glutamic acid", 33032],
  lysine: ["L-lysine", 5962],
  arginine: ["L-arginine", 6322],
  histidine: ["L-histidine", 6274],
};

function parseSdf(text, expectedCid) {
  const lines = text.replaceAll("\r\n", "\n").split("\n");
  const cid = Number.parseInt(lines[0].trim(), 10);
  if (cid !== expectedCid) {
    throw new Error(`Expected PubChem CID ${expectedCid}, received ${cid}`);
  }
  const counts = lines[3];
  const atomCount = Number.parseInt(counts.slice(0, 3), 10);
  const bondCount = Number.parseInt(counts.slice(3, 6), 10);
  if (!atomCount || !bondCount) {
    throw new Error(`CID ${cid} is not a supported V2000 structure`);
  }
  const atomLines = lines.slice(4, 4 + atomCount);
  const bondLines = lines.slice(4 + atomCount, 4 + atomCount + bondCount);
  const atoms = atomLines.map((line) => ({
    element: line.slice(31, 34).trim(),
    position: [
      Number.parseFloat(line.slice(0, 10)),
      Number.parseFloat(line.slice(10, 20)),
      Number.parseFloat(line.slice(20, 30)),
    ],
  }));
  const bonds = bondLines.map((line) => ({
    atoms: [
      Number.parseInt(line.slice(0, 3), 10) - 1,
      Number.parseInt(line.slice(3, 6), 10) - 1,
    ],
    order: Number.parseInt(line.slice(6, 9), 10),
  }));
  return { cid, atoms, bonds };
}

function formatNumber(value) {
  if (!Number.isFinite(value)) throw new Error("Non-finite molecule coordinate");
  return Number(value.toFixed(4)).toString();
}

function serializeMolecule(molecule) {
  const atoms = molecule.atoms
    .map(
      ({ element, position }) =>
        `      { element: "${element}", position: [${position
          .map(formatNumber)
          .join(", ")}] },`,
    )
    .join("\n");
  const bonds = molecule.bonds
    .map(
      ({ atoms: [a, b], order }) =>
        `      { atoms: [${a}, ${b}], order: ${order} },`,
    )
    .join("\n");
  return `{
    cid: ${molecule.cid},
    atoms: [
${atoms}
    ],
    bonds: [
${bonds}
    ],
  }`;
}

const molecules = {};
for (const [id, [name, expectedCid]] of Object.entries(COMPOUNDS)) {
  const endpoint = `https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/${encodeURIComponent(name)}/SDF?record_type=3d`;
  const response = await fetch(endpoint);
  if (!response.ok) {
    throw new Error(`PubChem request failed for ${name}: ${response.status}`);
  }
  molecules[id] = parseSdf(await response.text(), expectedCid);
  console.log(`${id}: CID ${molecules[id].cid}`);
}

const entries = Object.entries(molecules)
  .map(([id, molecule]) => `  ${JSON.stringify(id)}: ${serializeMolecule(molecule)},`)
  .join("\n");
const output = `/* This file is generated by scripts/fetch-molecules.mjs from PubChem
 * PUG REST 3D conformers. Do not edit molecule coordinates by hand. */
import type { AminoAcidId } from "./aminoAcids";
import type { Molecule } from "../lib/molecule";

export const MOLECULES = {
${entries}
} as const satisfies Record<AminoAcidId, Molecule>;
`;

const destination = fileURLToPath(
  new URL("../app/data/molecules.ts", import.meta.url),
);
await writeFile(destination, output);
